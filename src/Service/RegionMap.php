    /** Регион → слаг в URL. Заполняется один раз из CITY_REGION. */
    private ?array $slugs = null;

    /** Канонизирует город: тримит, чинит регистр, сводит алиасы. Пустая строка → null. */
    public function canonicalCity(?string $raw): ?string
    {
        if ($raw === null) {
            return null;
        }

        $city = trim(preg_replace('/\s+/u', ' ', $raw) ?? '');
        if ($city === '') {
            return null;
        }

        $lower = mb_strtolower($city);
        if (isset(self::ALIASES[$lower])) {
            return self::ALIASES[$lower];
        }

        // «вологда» → «Вологда»: сверяемся с картой без учёта регистра.
        foreach (array_keys(self::CITY_REGION) as $known) {
            if (mb_strtolower($known) === $lower) {
                return $known;
            }
        }

        return $city;
    }

    /** Регион канонизированного города или null, если город не в карте (fail-closed). */
    public function regionOf(?string $rawCity): ?string
    {
        $city = $this->canonicalCity($rawCity);

        return $city !== null ? (self::CITY_REGION[$city] ?? null) : null;
    }

    /** Все города карты, относящиеся к региону. */
    public function citiesOf(string $region): array
    {
        return array_keys(array_filter(self::CITY_REGION, static fn (string $r): bool => $r === $region));
    }

    /** Слаг региона для URL: «Ярославская область» → «yaroslavskaya-oblast». */
    public function slugOf(string $region): string
    {
        return $this->slugMap()[$region] ?? '';
    }

    /** Регион по слагу или null. */
    public function resolveSlug(string $slug): ?string
    {
        $found = array_search($slug, $this->slugMap(), true);

        return $found === false ? null : $found;
    }

    /** @return array<string,string> регион → слаг */
    public function slugMap(): array
    {
        if ($this->slugs === null) {
            $this->slugs = [];
            foreach (array_unique(array_values(self::CITY_REGION)) as $region) {
                $this->slugs[$region] = $this->transliterate($region);
            }
        }

        return $this->slugs;
    }

    private function transliterate(string $s): string
    {
        static $table = [
            'а' => 'a', 'б' => 'b', 'в' => 'v', 'г' => 'g', 'д' => 'd', 'е' => 'e', 'ё' => 'e',
            'ж' => 'zh', 'з' => 'z', 'и' => 'i', 'й' => 'y', 'к' => 'k', 'л' => 'l', 'м' => 'm',
            'н' => 'n', 'о' => 'o', 'п' => 'p', 'р' => 'r', 'с' => 's', 'т' => 't', 'у' => 'u',
            'ф' => 'f', 'х' => 'h', 'ц' => 'c', 'ч' => 'ch', 'ш' => 'sh', 'щ' => 'sch',
            'ъ' => '', 'ы' => 'y', 'ь' => '', 'э' => 'e', 'ю' => 'yu', 'я' => 'ya',
        ];

        $out = strtr(mb_strtolower($s), $table);
        $out = preg_replace('/[^a-z0-9]+/', '-', $out) ?? '';

        return trim($out, '-');
    }
