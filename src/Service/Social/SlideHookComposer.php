<?php

declare(strict_types=1);

namespace App\Service\Social;

use App\Entity\Brand;

/**
 * Хук-надпись на первом слайде — то, что решает, останется зритель или пролистнёт.
 *
 * Собран НЕ из поисковых фраз (запрос Вордстата описывает намерение искать, а не удерживает
 * внимание), а по канону:
 *
 * - **Шварц, «Breakthrough Advertising»**: копия не создаёт желание, а канализирует уже
 *   существующее, и заголовок обязан соответствовать уровню осведомлённости. Наш зритель
 *   знает, что хочет русские марки вместо ушедших, но про КОНКРЕТНЫЙ бренд не знает ничего →
 *   имя бренда в хук не ставим, ставим уже существующее желание (география, «своё»).
 * - **Чалдини, «Pre-Suasion»**: внимание удерживают само-релевантное, незавершённое и
 *   загадочное. Само-релевантность даёт город, незавершённость — счётчик «3/10» на слайдах.
 * - **Лёвенштайн (information gap) / эффект Зейгарник / Хиты, «Made to Stick»**: разрыв в
 *   знании нужно открыть и НЕ закрывать в самом хуке — иначе смотреть дальше незачем.
 * - **Огилви**: конкретика вместо превосходных степеней (и это же совпадает с нашим запретом
 *   на banned-AI-слова).
 *
 * Формулировки чередуются детерминированно по id поста, чтобы соседние посты в ленте не
 * читались одинаково, но повторный рендер того же поста давал тот же текст.
 */
class SlideHookComposer
{
    /**
     * Шаблоны с городом: город — самый сильный само-релевантный якорь, который у нас есть
     * (заполнен у 289 из 292 брендов-кандидатов).
     *
     * ⚠️ Город подставляется ТОЛЬКО в именительном падеже: «из %s» дало бы «из Санкт-Петербург».
     * Морфологию не тянем — вместо неё формулировки, где название стоит отдельным блоком или
     * подлежащим. Числительное согласуем сами (plural()).
     *
     * @var list<string>
     */
    private const WITH_CITY = [
        '%s. %s',
        '%s шьёт. %s',
        '%s, не маркетплейс. %s',
    ];

    /** @var list<string> */
    private const WITHOUT_CITY = [
        '%s российского бренда',
        'Шьют в России. %s',
    ];

    public function compose(Brand $brand, int $itemCount, int $seed): string
    {
        $items = $this->plural($itemCount, 'вещь', 'вещи', 'вещей');
        $city = trim((string) $brand->getCity());

        if ($city !== '') {
            return sprintf(self::WITH_CITY[$seed % count(self::WITH_CITY)], $city, $items);
        }

        return sprintf(self::WITHOUT_CITY[$seed % count(self::WITHOUT_CITY)], $items);
    }

    /** «2 вещи», «5 вещей» — без согласования хук читается как машинный. */
    private function plural(int $n, string $one, string $few, string $many): string
    {
        $mod100 = $n % 100;
        $mod10 = $n % 10;

        if ($mod100 >= 11 && $mod100 <= 14) {
            return $n . ' ' . $many;
        }
        if ($mod10 === 1) {
            return $n . ' ' . $one;
        }
        if ($mod10 >= 2 && $mod10 <= 4) {
            return $n . ' ' . $few;
        }

        return $n . ' ' . $many;
    }
}
