<?php

declare(strict_types=1);

namespace App\Service\Social;

/**
 * Текст поста-галереи как ОДИН сценарий на три позиции клипа, а не три независимые надписи.
 *
 * Зачем сценарий, а не набор шаблонов: три беседы подряд («сколько бы взял?» → «запомни
 * номер» → «пиши цифру») должны спрашивать ОДНО И ТО ЖЕ. Если хук задаёт вопрос про
 * количество, а CTA просит номер вещи, зритель теряет задачу и не отвечает — комментарий-гейт
 * ломается ровно на несостыковке. Поэтому связка hook/retention/cta собирается вместе
 * (SlideScriptComposer) и здесь переносится как целое.
 *
 * Драматургия трёх позиций:
 * 1. hook (первый кадр, ~1.5 с) — открыть разрыв в знании и НЕ закрывать его
 *    (Лёвенштайн/Зейгарник, Хиты «Made to Stick»);
 * 2. retention (середина) — то, чего счётчик «3/10» и полоса прогресса дать не могут: они
 *    сообщают, СКОЛЬКО осталось, но не ЗАЧЕМ смотреть. Здесь — задача зрителю или причина;
 * 3. ctaLines (последний кадр) — собрать действие: первая строка крупно = основной запрос
 *    (комментарий), дальше мельче = сохранение и пересылка.
 *
 * Ширины строк живут здесь, а не в рендерере: это общий контракт двух сторон — тот, кто
 * пишет слова, обязан знать, во сколько знаков они обязаны влезть, иначе перенос выкинет
 * строку с напряжением и от хука останется ярлык.
 */
final class SlideScript
{
    /**
     * Крупный текст: 26 знаков в строке при кегле 54 на холсте 1080 и максимум ДВЕ строки —
     * слайд живёт 1.5 секунды, третью строку клиповый зритель прочитать не успеет.
     */
    public const HOOK_MAX_CHARS = 26;
    public const MAX_HOOK_LINES = 2;

    /** Вторичные строки CTA (сохранение/пересылка) — кегль мельче, значит знаков влезает больше. */
    public const CTA_MAX_CHARS = 34;

    /**
     * @param list<string> $ctaLines первая строка — основной запрос (рисуется крупно),
     *                               остальные — вторичные (мельче)
     */
    public function __construct(
        public readonly string $hook,
        public readonly string $retention,
        public readonly array $ctaLines,
    ) {
    }
}
