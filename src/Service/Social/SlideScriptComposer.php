<?php

declare(strict_types=1);

namespace App\Service\Social;

use App\Entity\Brand;

/**
 * Сценарий надписей поста-галереи: хук на первом кадре, удерживающая реплика в середине,
 * CTA на последнем. Пришёл на место SlideHookComposer, который отдавал только первый кадр и
 * только ярлыком («Пермь. 9 вещей», «Москва шьёт»).
 *
 * ПОЧЕМУ ЯРЛЫК НЕ РАБОТАЛ. «Пермь. 9 вещей» — это подпись к экспонату: сообщает факт и
 * закрывает вопрос в тот же момент, когда его открыл. По Лёвенштайну (information gap) и
 * эффекту Зейгарник внимание держит НЕЗАКРЫТАЯ петля, поэтому каждый хук здесь оставляет
 * зрителю нерешённую задачу (сколько тут моего? какая станет моей?), решаемую только
 * просмотром до конца.
 *
 * КАНОН, по которому собраны формулировки:
 * - **Шварц, «Breakthrough Advertising»**: копия не создаёт желание, а канализирует уже
 *   существующее, и заголовок обязан попадать в уровень осведомлённости. Зритель хочет
 *   русские марки вместо ушедших, но про КОНКРЕТНЫЙ бренд не знает ничего → имя бренда не
 *   ведёт (оно ничего не обещает), ведёт то, что зритель уже хочет: своё, поближе, не из
 *   чужой выдачи.
 * - **Чалдини, «Pre-Suasion»**: внимание удерживает само-релевантное, незавершённое и
 *   загадочное. Само-релевантность даёт город и прямое обращение на «ты», незавершённость —
 *   вопрос без ответа в кадре.
 * - **Хиты, «Made to Stick»**: разрыв открыть и не закрывать; ответ — в конце, не в хуке.
 * - **Огилви**: конкретика вместо превосходных степеней (совпадает с запретом на
 *   banned-AI-слова: ни «уникальный», ни «лидирующий» тут физически не появятся).
 * - Современная специфика короткого видео: первые ~3 секунды решают раздачу, а сильнейший
 *   доступный сигнал качества — пересылка в личку и комментарий. Отсюда CTA из трёх слоёв:
 *   комментарий (основной, самый дешёвый ответ — цифра), сохранение, пересылка.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ (граница проверяемости — правило дороже красоты):
 * - «этого нет на маркетплейсах», «дешевле, чем на WB», «шьют вручную», «лимитированная
 *   партия» — по конкретному бренду НЕ проверено, значит не говорим;
 * - «шьёт»/«сшито в России» — место производства у бренда в базе не подтверждено (российский
 *   бренд вполне может отшиваться за границей), поэтому старая формулировка «Москва шьёт»
 *   выброшена не только как ярлык, но и как недоказуемое утверждение;
 * - цены и «от N ₽» — товаров в базе нет (48 позиций на один бренд), брать нечем;
 * - фразы Вордстата — общие слова («горе» с 8.3 млн показов у бренда «Горе»), это не спрос на
 *   бренд и в кадр не идут;
 * - год основания — есть у 61 бренда из 292, отдельная ветка ради 20% покрытия не окупается.
 * Проверяемые опоры остаются три: город (289/292), число фото (всегда) и платформенный факт
 * про комиссию маркетплейса 30–67% (PillarCaptionSource::PILLARS).
 *
 * ГРАММАТИКА. Город подставляется ТОЛЬКО в именительном падеже — морфологию не тянем, а «из
 * Санкт-Петербург» это брак. Поэтому во всех шаблонах город стоит отдельным блоком (перед
 * точкой/запятой) и никогда не идёт после предлога. Числительное согласуется plural().
 *
 * РОД. Обращение к зрителю — только в формах без рода (будущее время, повелительное,
 * безличное): аудитория русских марок перекошена в женскую сторону, а «взял бы» звучало бы
 * мимо половины зрителей.
 *
 * РОТАЦИЯ детерминирована по seed (вызывающий передаёт id бренда): соседние бренды в ленте
 * звучат по-разному, повторный рендер того же бренда даёт тот же текст, и — что важнее —
 * ветки A/B logo_first/logo_last получают ОДИН И ТОТ ЖЕ текст, иначе эксперимент сравнивал бы
 * заодно и копию.
 */
class SlideScriptComposer
{
    /**
     * Сценарии. Каждый — одна связка «разрыв → задача → сбор действия» с одним и тем же
     * запросом от начала до конца.
     *
     * city/nocity — первая строка хука (само-релевантный якорь: город). Числа тут НЕТ намеренно:
     * «сколько осталось» уже говорят счётчик и полоса прогресса на каждом кадре, а слово для
     * счёта у нас непригодное — «кадры» зрителю ничего не обещают (жаргон), «вещи» обещают то,
     * чего мы не проверяли (в галерее попадаются витрины и лукбук-сцены). Освободившееся место
     * целиком уходит второй строке, где и живёт напряжение.
     * tension — вторая строка хука, та самая незакрытая петля.
     * retention — середина клипа, две строки.
     * cta — основной запрос на последнем кадре (крупная строка).
     *
     * Якорь идёт БЕЗ точки на конце — это подпись-строка, а не предложение.
     *
     * @var list<array{city:string,nocity:string,tension:string,retention:string,cta:string}>
     */
    private const SCRIPTS = [
        // A. «Пересчёт». Канализирует желание найти своё среди русских марок; петля —
        // посчитать нельзя, не досмотрев (Лёвенштайн). Ответ на вопрос зрителя «а мне-то
        // тут что?» — самый дешёвый из возможных ответов в комментарий: цифра.
        [
            'city'      => '{city}',
            'nocity'    => 'Русский бренд',
            'tension'   => 'Сколько тут твоего?',
            'retention' => "Считай, не листай.\nВ конце — куда писать.",
            'cta'       => 'Сколько? Пиши цифру.',
        ],
        // B. «Один — твой». Предсказание про зрителя (Чалдини: само-релевантное), а не
        // утверждение про бренд — проверяемость не страдает. Заодно заранее сажает то
        // действие, которое просим в конце: сохранение.
        [
            'city'      => '{city}',
            'nocity'    => 'Русский бренд',
            'tension'   => 'Один — точно твой.',
            'retention' => "Один из них — твой.\nЗапомни номер.",
            'cta'       => 'Какой твой? Номер ниже.',
        ],
        // C. «Тебе это не показывали». Прямо по Шварцу: бренд зрителю неизвестен, и это не
        // недостаток, а сам разрыв. Середина отдаёт ПРИЧИНУ (платформенный факт про
        // комиссию) — то, чего счётчик и полоса прогресса дать не могут, и то, что делает
        // посыл внятным: вот почему такие бренды не попадаются на глаза.
        [
            'city'      => '{city}',
            'nocity'    => 'Русский бренд',
            'tension'   => 'Тебе это не показывали.',
            'retention' => "Маркетплейс забрал бы\n30–67% с каждой продажи.",
            'cta'       => 'Твоё или нет? Пиши.',
        ],
    ];

    /**
     * Вторичные строки CTA — одни и те же во всех сценариях, и это осознанно: повторяемость
     * приучает аудиторию к действию, а вариативность тут ничего не добавляет.
     *
     * Порядок = порядок ценности сигнала. Сохранение просим раньше пересылки, потому что
     * «сохрани» выполняется в одно касание, а пересылка требует выбрать человека; зато формула
     * пересылки называет получателя («кто ищет такое») — без адресата просьба переслать
     * повисает в воздухе.
     *
     * @var list<string>
     */
    private const CTA_SECONDARY = [
        'Сохрани, чтобы не потерять.',
        'Отправь тому, кто ищет такое.',
    ];

    public function compose(Brand $brand, int $seed): SlideScript
    {
        $script = self::SCRIPTS[abs($seed) % count(self::SCRIPTS)];

        return new SlideScript(
            hook: $this->anchor($script, $this->city($brand)) . "\n" . $script['tension'],
            retention: $script['retention'],
            ctaLines: [$script['cta'], ...self::CTA_SECONDARY],
        );
    }

    /**
     * Первая строка хука — город. Если название города в строку плашки не влезает (длинные
     * составные вроде «Комсомольск-на-Амуре-и-Дальше»), падаем на нейтральный якорь: вторая
     * строка, в которой всё напряжение, не должна выдавливаться переносом.
     *
     * @param array{city:string,nocity:string,tension:string,retention:string,cta:string} $script
     */
    private function anchor(array $script, string $city): string
    {
        if ($city !== '') {
            $candidate = strtr($script['city'], ['{city}' => $city]);
            if (mb_strlen($candidate) <= SlideScript::HOOK_MAX_CHARS) {
                return $candidate;
            }
        }

        return $script['nocity'];
    }

    /**
     * Город бренда в том виде, в каком его можно ставить в кадр. Значения в базе чистые
     * (проверено: «Москва», «Санкт-Петербург», «Ростов-на-Дону» — именительный, без «г.»),
     * поэтому нормализация минимальная: убрать пробелы по краям.
     */
    private function city(Brand $brand): string
    {
        return trim((string) $brand->getCity());
    }

}
